-- ============================================================
--  SIANNA TRAVEL — Suscripciones a notificaciones push (admin PWA)
--  Ejecutar como "postgres" conectado a la base "sianna" (DBGate).
--  Requiere que exista admin_users (06_admin_users.sql).
-- ============================================================

CREATE TABLE IF NOT EXISTS push_subscriptions (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id  BIGINT NOT NULL REFERENCES admin_users(id) ON DELETE CASCADE,
  endpoint    TEXT NOT NULL,
  p256dh      TEXT NOT NULL,
  auth        TEXT NOT NULL,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_push_subscriptions_endpoint ON push_subscriptions(endpoint);
CREATE INDEX IF NOT EXISTS idx_push_subscriptions_usuario ON push_subscriptions(usuario_id);

-- El backend (sianna_app) registra, lee y limpia suscripciones.
GRANT SELECT, INSERT, UPDATE, DELETE ON push_subscriptions TO sianna_app;
GRANT USAGE, SELECT ON SEQUENCE push_subscriptions_id_seq TO sianna_app;
